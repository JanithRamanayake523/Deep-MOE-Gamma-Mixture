#!/usr/bin/env python
"""Materialise the E8 ablation grid as training configs (base-inheriting YAML).

    python scripts/make_ablations.py --spec configs/experiments/e8_ablations.yaml
writes configs/train/ablations/<variant>.yaml and prints the training commands.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path

import yaml


def nest(overrides: dict) -> dict:
    out: dict = {}
    for key, val in overrides.items():
        cur = out
        parts = key.split(".")
        for p in parts[:-1]:
            cur = cur.setdefault(p, {})
        cur[parts[-1]] = val
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec", required=True)
    ap.add_argument("--dest", default="configs/train/ablations")
    args = ap.parse_args()
    with open(args.spec, encoding="utf-8") as f:
        spec = yaml.safe_load(f)
    dest = Path(args.dest)
    dest.mkdir(parents=True, exist_ok=True)
    base_rel = os.path.relpath(Path(spec["base"]).resolve(), dest.resolve()).replace("\\", "/")
    run_root = spec.get("run_root", "runs/ablations")
    for name, overrides in spec["variants"].items():
        body = nest(dict(overrides or {}))
        body.setdefault("training", {})["out_dir"] = f"{run_root}/{name}"
        path = dest / f"{name}.yaml"
        with open(path, "w", encoding="utf-8") as f:
            f.write(f"# E8 ablation '{name}' (generated by scripts/make_ablations.py)\n")
            yaml.safe_dump({"base": base_rel, **body}, f, sort_keys=False)
        print(f"python scripts/train_aem.py --config {path.as_posix()}")


if __name__ == "__main__":
    main()
