#!/usr/bin/env python
"""Generate the v2 training and experiment configs (run once; the outputs are
committed so every run is traceable to a file). Edit here, then re-run:

    python configs/make_configs.py
"""
from __future__ import annotations

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent
TRAIN, EXP = ROOT / "train", ROOT / "experiments"


def dump(path: Path, body: dict, header: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"# {header}\n# generated by configs/make_configs.py\n")
        yaml.safe_dump(body, f, sort_keys=False, default_flow_style=None)


# ----------------------------------------------------------------------------- training: families
