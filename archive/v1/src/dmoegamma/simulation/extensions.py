"""Simulator-only scope extensions (RESEARCH_METHODOLOGY.md, Study 5 / RQ4).

These modify the *data-generating process* only; the amortized estimator is
simply retrained on the extended simulator -- the capability WH-MCLUST lacks.
"""
from __future__ import annotations

import numpy as np
from scipy.stats import gamma as gamma_dist
from scipy.stats import norm

from ..params import Theta
from .mixture import sample


def sample_with_copula(
    theta: Theta,
    correlations: list[np.ndarray],
    n: int,
    rng: np.random.Generator | int | None = None,
) -> tuple[np.ndarray, np.ndarray]:
    """Multivariate gamma mixture with dependent marginals via Gaussian copula.

    correlations : list of g correlation matrices, each (k, k). Component i's
    observation is generated by z_p = F^{-1}_{alpha_ip, beta_ip}(Phi(u_p)) with
    u ~ N_k(0, R_i). Base paper explicitly lists dependent marginals as future
    work its own pipeline cannot handle.
    """
    rng = np.random.default_rng(rng)
    if len(correlations) != theta.g:
        raise ValueError("one correlation matrix per component")
    labels = rng.choice(theta.g, size=n, p=theta.pi)
    X = np.empty((n, theta.k))
    for i in range(theta.g):
        idx = labels == i
        m = int(idx.sum())
        if m == 0:
            continue
        R = np.asarray(correlations[i], dtype=np.float64)
        U = rng.multivariate_normal(np.zeros(theta.k), R, size=m)
        P = norm.cdf(U)
        for p in range(theta.k):
            X[idx, p] = gamma_dist.ppf(np.clip(P[:, p], 1e-10, 1 - 1e-10),
                                       a=theta.alpha[i, p], scale=theta.beta[i, p])
    return X, labels


def add_location(X: np.ndarray, delta: np.ndarray, labels: np.ndarray) -> np.ndarray:
    """Shift to a 3-parameter gamma: x -> x + delta_{component, marginal}."""
    delta = np.asarray(delta, dtype=np.float64)
    return X + delta[labels]


def apply_right_censoring(
    X: np.ndarray, censor_times: np.ndarray
) -> tuple[np.ndarray, np.ndarray]:
    """Right-censor observations: returns (observed_values, event_indicators).

    event = 1 if X <= censor_times (observed), else 0 (censored at censor_times).
    The censoring indicator becomes an extra model input at training time.
    """
    observed = np.minimum(X, censor_times)
    events = (X <= censor_times).astype(np.int64)
    return observed, events


